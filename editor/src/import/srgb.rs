/// The byte for `light`, which is 0 for none and 1 for full. Anything
/// that is not a number is none.
pub fn byte(light: f32) -> u8 {
    BEGINS.partition_point(|begin| *begin <= light) as u8
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn light_is_turned_into_the_screens_bytes_by_the_table() {
        // the ends, the middle grey every renderer agrees on (18% light is byte 118), and values out of range
        assert_eq!((byte(0.0), byte(1.0), byte(0.18), byte(0.5), byte(-3.0), byte(7.0), byte(f32::NAN)), (0, 255, 118, 188, 0, 255, 0));
        // rising all the way, each byte reached
        assert!((0..=1000).map(|i| byte(i as f32 / 1000.0)).collect::<Vec<u8>>().windows(2).all(|w| w[0] <= w[1]));
        assert!(BEGINS.windows(2).all(|w| w[0] < w[1]));
    }
}
